local L=dofile("Workshop/MoreLife/Contents/mods/MoreLife/42/media/lua/shared/MoreLife/ContainerLocks.lua")
local now=0
local a=L.new(function() return now end,30)
local t=assert(a.acquire("crate1","p1"))
local x,reason,owner=a.acquire("crate1","p2")
assert(x==nil and reason=="busy" and owner=="p1")
assert(a.acquire("crate2","p2"))
assert(not a.release("crate1","p2",t))
assert(not a.renew("crate1","p1",t+1))
now=20; assert(a.renew("crate1","p1",t))
now=31; assert(not a.acquire("crate1","p2"))
now=51; local t2=assert(a.acquire("crate1","p2"))
assert(t2~=t and not a.release("crate1","p1",t))
a.disconnect("p2"); assert(a.acquire("crate1","p3"))
now=100; a.sweep(); assert(a.acquire("crate1","p4"))
assert(a.release("crate1","p4",select(3,a.acquire("crate1","p4")))==false)
print("Container lock tests passed")
