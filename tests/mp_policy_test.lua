local P=dofile("Workshop/MoreLife/Contents/mods/MoreLife/42/media/lua/shared/MoreLife/MPPolicy.lua")
assert(P.reading(nil)==nil)
assert(P.reading({MinutesPerPage=0})==nil)
assert(P.reading({MinutesPerPage=-1})==nil)
assert(P.reading({MinutesPerPage=math.huge})==nil)
assert(P.reading({MinutesPerPage=0/0})==nil)
assert(P.reading({MinutesPerPage="bad"})==nil)
assert(P.reading({MinutesPerPage="0.1"})==0.1)
assert(P.summary({MinutesPerPage=0.1}):find("20x",1,true))
assert(P.summary({MinutesPerPage=2}):find("1x",1,true))
print("MP policy assertions passed")
